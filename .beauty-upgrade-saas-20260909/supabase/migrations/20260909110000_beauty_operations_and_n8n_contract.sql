returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_comanda_status text;
  v_total numeric;
  v_pagamento_base numeric;
  v_taxa_percentual numeric := 0;
  v_custo_insumos numeric := 0;
  v_falta record;
  v_resultado jsonb;
begin
  if not private.usuario_tem_tipo_empresa(
    p_id_empresa,
    array['dono'::public.tipos_usuarios, 'gerente'::public.tipos_usuarios,
          'recepcionista'::public.tipos_usuarios]
  ) then raise exception 'Voce nao possui permissao para fechar comandas.'; end if;

  select c.status, coalesce(c.valor_total, 0)
  into v_comanda_status, v_total
  from public.comandas c
  where c.id_empresa = p_id_empresa and c.id = p_comanda_id
  for update;
  if not found then raise exception 'Comanda nao encontrada.'; end if;
  if v_comanda_status <> 'aberta' then
    raise exception 'Apenas comandas abertas podem ser fechadas.';
  end if;
  if jsonb_typeof(coalesce(p_consumos, '[]'::jsonb)) <> 'array' then
    raise exception 'A lista de consumos e invalida.';
  end if;

  delete from public.consumos_insumos_comanda
  where id_empresa = p_id_empresa and id_comanda = p_comanda_id;

  for v_item in select value from jsonb_array_elements(coalesce(p_consumos, '[]'::jsonb))
  loop
    insert into public.consumos_insumos_comanda (
      id_empresa,id_comanda,id_comanda_item,id_servico,id_produto,id_funcionario,
      quantidade_sugerida,quantidade_utilizada,custo_unitario_snapshot,
      descontar_comissao
    )
    select p_id_empresa,p_comanda_id,ci.id,ci.id_servico,
      p.id,ci.id_funcionario,
      coalesce(si.quantidade_padrao, 0),
      nullif(v_item->>'quantidade', '')::numeric,
      coalesce(p.custo_medio, 0),
      coalesce((v_item->>'descontar_comissao')::boolean,
               si.descontar_comissao, true)
    from public.comandas_itens ci
    join public.produtos p
      on p.id_empresa = ci.id_empresa
     and p.id = nullif(v_item->>'id_produto', '')::bigint
     and p.ativo and p.controla_estoque
    left join public.servicos_insumos si
      on si.id_empresa = ci.id_empresa and si.id_servico = ci.id_servico
     and si.id_produto = p.id and si.ativo
    where ci.id_empresa = p_id_empresa and ci.id_comanda = p_comanda_id
      and ci.id = nullif(v_item->>'id_comanda_item', '')::bigint
      and ci.tipo_item = 'servico'
      and nullif(v_item->>'quantidade', '')::numeric > 0;
    if not found then
      raise exception 'Consumo invalido: confira servico, produto e quantidade.';
    end if;
  end loop;

  select p.nome, p.estoque_atual,
         coalesce(v.venda, 0) + coalesce(c.consumo, 0) necessario
  into v_falta
  from public.produtos p
  left join (
    select ci.id_produto, sum(ci.quantidade) venda
    from public.comandas_itens ci
    where ci.id_empresa = p_id_empresa and ci.id_comanda = p_comanda_id
      and ci.tipo_item = 'produto'
    group by ci.id_produto
  ) v on v.id_produto = p.id
  left join (
    select ci.id_produto, sum(ci.quantidade_utilizada) consumo
    from public.consumos_insumos_comanda ci
    where ci.id_empresa = p_id_empresa and ci.id_comanda = p_comanda_id
    group by ci.id_produto
  ) c on c.id_produto = p.id
  where p.id_empresa = p_id_empresa and p.controla_estoque
    and p.estoque_atual < coalesce(v.venda, 0) + coalesce(c.consumo, 0)
  limit 1;
  if found then
    raise exception 'Estoque insuficiente para %. Disponivel: %, necessario: %.',
      v_falta.nome, v_falta.estoque_atual, v_falta.necessario;
  end if;

  if p_situacao_pagamento <> 'a_receber' then
    select f.taxa_percentual into v_taxa_percentual
    from public.formas_pagamento f
    where f.id_empresa = p_id_empresa and f.id = p_id_forma_pagamento and f.ativo;
    if not found then raise exception 'Forma de pagamento invalida.'; end if;
  end if;
  v_pagamento_base := case
    when p_situacao_pagamento = 'pago' then v_total
    when p_situacao_pagamento = 'parcial' then coalesce(p_valor_pagamento, 0)
    else 0 end;
  select coalesce(sum(c.custo_total), 0) into v_custo_insumos
  from public.consumos_insumos_comanda c
  where c.id_empresa = p_id_empresa and c.id_comanda = p_comanda_id;

  update public.comandas
  set taxa_pagamento_snapshot = round(v_pagamento_base * coalesce(v_taxa_percentual, 0) / 100, 2),
      custo_insumos_snapshot = round(v_custo_insumos, 2), updated_at = now()
  where id_empresa = p_id_empresa and id = p_comanda_id;

  v_resultado := public.fechar_comanda_com_pagamento(
    p_comanda_id,p_id_empresa,p_situacao_pagamento,p_data_vencimento,
    p_id_forma_pagamento,p_id_sessao_caixa,p_data_pagamento,
    p_valor_pagamento,p_referencia,p_observacoes_pagamento
  );
  return v_resultado || jsonb_build_object(
    'taxa_pagamento', round(v_pagamento_base * coalesce(v_taxa_percentual, 0) / 100, 2),
    'custo_insumos', round(v_custo_insumos, 2)
  );
end;
$$;

create or replace function public.resumo_fechamento_semanal(
  p_id_empresa bigint,
  p_data_inicio date,
  p_data_fim date
)
returns table (
  id_funcionario bigint,
  funcionario_nome text,
  producao_bruta numeric,
  descontos numeric,
  taxas_pagamento numeric,
  custos_insumos numeric,
  base_comissao numeric,
  comissao_gerada numeric,
  ajustes numeric,
  valor_pago numeric,
  saldo_a_pagar numeric
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.usuario_tem_tipo_empresa(
    p_id_empresa,
    array['dono'::public.tipos_usuarios, 'gerente'::public.tipos_usuarios]
  ) then raise exception 'Voce nao possui permissao para consultar o fechamento.'; end if;
  if p_data_inicio is null or p_data_fim is null or p_data_fim < p_data_inicio
     or p_data_fim - p_data_inicio > 62 then
    raise exception 'Periodo de fechamento invalido.';
  end if;

  return query
  select f.id, f.nome,
    round(coalesce(sum(l.base_original) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.desconto_rateado) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.taxa_pagamento_rateada) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.custo_insumos_rateado) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.base_calculo) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.valor_comissao) filter (where l.tipo_origem = 'comanda'), 0), 2),
    round(coalesce(sum(l.valor_comissao) filter (where l.tipo_origem = 'ajuste'), 0), 2),
    round(coalesce(sum(l.valor_pago), 0), 2),
    round(coalesce(sum(greatest(l.valor_comissao - l.valor_pago, 0))
      filter (where l.status in ('liberada', 'parcial')), 0), 2)
  from public.funcionarios f
  join public.lancamentos_comissao l
    on l.id_empresa = f.id_empresa and l.id_funcionario = f.id
   and l.competencia between p_data_inicio and p_data_fim
   and l.status <> 'estornada'
  where f.id_empresa = p_id_empresa
  group by f.id, f.nome
  order by f.nome;
end;
$$;

create or replace function public.registrar_fechamento_semanal(
  p_id_empresa bigint,
  p_data_inicio date,
  p_data_fim date,
  p_id_forma_pagamento bigint,
  p_id_sessao_caixa bigint default null,
  p_pago_em timestamptz default now(),
  p_observacoes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_funcionario record;
  v_itens jsonb;
  v_pagamento bigint;
  v_total numeric := 0;
  v_quantidade integer := 0;
begin
  if not private.usuario_tem_tipo_empresa(
    p_id_empresa,
    array['dono'::public.tipos_usuarios, 'gerente'::public.tipos_usuarios]
  ) then raise exception 'Voce nao possui permissao para fechar comissoes.'; end if;
  if p_data_inicio is null or p_data_fim is null or p_data_fim < p_data_inicio
     or p_data_fim - p_data_inicio > 62 then raise exception 'Periodo invalido.'; end if;
  if not exists (
    select 1 from public.formas_pagamento f
    where f.id_empresa = p_id_empresa and f.id = p_id_forma_pagamento and f.ativo
  ) then raise exception 'Forma de pagamento invalida.'; end if;

  for v_funcionario in
    select l.id_funcionario,
      jsonb_agg(jsonb_build_object(
        'id_lancamento_comissao', l.id,
        'valor', round(l.valor_comissao - l.valor_pago, 2)
      ) order by l.id) itens,
      round(sum(l.valor_comissao - l.valor_pago), 2) total
    from public.lancamentos_comissao l
    where l.id_empresa = p_id_empresa
      and l.competencia between p_data_inicio and p_data_fim
      and l.status in ('liberada', 'parcial')
      and l.valor_comissao > l.valor_pago
    group by l.id_funcionario
  loop
    v_itens := v_funcionario.itens;
    v_pagamento := public.registrar_pagamento_comissao(
      p_id_empresa, v_funcionario.id_funcionario, p_id_forma_pagamento,
      p_id_sessao_caixa, coalesce(p_pago_em, now()), p_data_inicio, p_data_fim,
      concat_ws(E'\n', 'Fechamento semanal ' || p_data_inicio || ' a ' || p_data_fim,
        nullif(btrim(p_observacoes), '')), v_itens
    );
    v_total := v_total + v_funcionario.total;
    v_quantidade := v_quantidade + 1;
  end loop;
  if v_quantidade = 0 then raise exception 'Nao existem comissoes liberadas neste periodo.'; end if;
  return jsonb_build_object('profissionais', v_quantidade, 'valor_total', v_total);
end;
$$;

create or replace function public.n8n_reservar_mensagens(p_limite integer default 20)
returns table (
  id bigint, id_empresa bigint, canal text, destinatario text, assunto text,
  conteudo text, dados_template jsonb, tentativas integer, max_tentativas integer
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  with escolhidas as (
    select m.id
    from public.fila_mensagens m
    where m.status in ('pendente', 'erro')
      and m.agendada_para <= now()
      and coalesce(m.proxima_tentativa_em, now()) <= now()
      and m.tentativas < m.max_tentativas
    order by m.prioridade desc, m.agendada_para, m.id
    for update skip locked
    limit least(greatest(coalesce(p_limite, 20), 1), 100)
  ), atualizadas as (
    update public.fila_mensagens m
    set status = 'processando', processamento_iniciado_em = now(),
        tentativas = tentativas + 1, updated_at = now()
    from escolhidas e where m.id = e.id
    returning m.*
  )
  select a.id,a.id_empresa,a.canal,a.destinatario,a.assunto,a.conteudo,
    a.dados_template,a.tentativas,a.max_tentativas
  from atualizadas a order by a.prioridade desc,a.agendada_para,a.id;
end;
$$;

create or replace function public.n8n_registrar_resultado_mensagem(
