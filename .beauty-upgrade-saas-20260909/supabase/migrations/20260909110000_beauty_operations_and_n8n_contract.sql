create or replace function public.n8n_processar_resposta_whatsapp(
  p_id_empresa bigint,
  p_identificador_externo text,
  p_remetente text,
  p_conteudo text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existente public.eventos_mensagens_recebidas%rowtype;
  v_cliente public.clientes%rowtype;
  v_agendamento public.agendamentos%rowtype;
  v_texto text := upper(btrim(coalesce(p_conteudo,'')));
  v_acao text := 'ignorada';
  v_emitido jsonb;
  v_link text;
  v_resposta jsonb;
begin
  if nullif(btrim(p_identificador_externo),'') is null
     or nullif(regexp_replace(p_remetente,'[^0-9]','','g'),'') is null then
    raise exception 'Identificador e remetente sao obrigatorios.';
  end if;
  select * into v_existente from public.eventos_mensagens_recebidas e
  where e.id_empresa = p_id_empresa and e.identificador_externo = p_identificador_externo;
  if found then return v_existente.resposta || jsonb_build_object('duplicated',true); end if;

  select * into v_cliente from public.clientes c
  where c.id_empresa = p_id_empresa
    and right(regexp_replace(coalesce(c.telefone_e164,c.telefone_principal,''),'[^0-9]','','g'),11)
      = right(regexp_replace(p_remetente,'[^0-9]','','g'),11)
  order by c.updated_at desc,c.id desc limit 1;
  if not found then
    v_acao := 'sem_agendamento';
    v_resposta := jsonb_build_object('action',v_acao,'message','Cliente nao identificado.');
  else
    select * into v_agendamento from public.agendamentos a
    where a.id_empresa = p_id_empresa and a.id_cliente = v_cliente.id
      and a.inicio > now() and a.status in ('aguardando_confirmacao','aguardando_pagamento','confirmado')
    order by a.inicio limit 1 for update;
    if not found then
      v_acao := 'sem_agendamento';
      v_resposta := jsonb_build_object('action',v_acao,'message','Nenhum agendamento futuro encontrado.');
    elsif v_texto in ('1','SIM','CONFIRMAR','CONFIRMO') then
      if v_agendamento.sinal_status = 'pendente' then
        v_acao := 'pagamento_pendente';
        v_resposta := jsonb_build_object('action',v_acao,'bookingId',v_agendamento.id,
          'message','O sinal ainda precisa ser pago antes da confirmacao.');
      else
        perform private.aplicar_acao_agendamento_cliente(
          p_id_empresa,v_agendamento.id,'confirmar',null,'whatsapp_n8n',v_cliente.id,null
        );
        v_acao := 'confirmada';
        v_resposta := jsonb_build_object('action',v_acao,'bookingId',v_agendamento.id,
          'message','Presenca confirmada com sucesso.');
      end if;
    elsif v_texto in ('2','REMARCAR','REAGENDAR') then
      v_emitido := private.emitir_token_link_agendamento(
        p_id_empresa,v_agendamento.id,'gerenciar',interval '2 days'
      );
      v_link := '/confirmacao/acessar?token=' || (v_emitido->>'token');
      v_acao := 'reagendamento_solicitado';
      v_resposta := jsonb_build_object('action',v_acao,'bookingId',v_agendamento.id,
        'relativeLink',v_link,'expiresAt',v_emitido->>'expires_at',
        'message','Abra o link seguro para escolher um novo horario.');
    else
      v_resposta := jsonb_build_object('action',v_acao,'bookingId',v_agendamento.id,
        'message','Resposta nao reconhecida. Envie 1 para confirmar ou 2 para reagendar.');
    end if;
  end if;

  insert into public.eventos_mensagens_recebidas (
    id_empresa,identificador_externo,remetente,conteudo,id_cliente,id_agendamento,
    acao,resposta,processado_em
  ) values (
    p_id_empresa,btrim(p_identificador_externo),btrim(p_remetente),left(p_conteudo,500),
    v_cliente.id,v_agendamento.id,v_acao,v_resposta,now()
  );
  return v_resposta || jsonb_build_object('duplicated',false);
exception when unique_violation then
  select * into v_existente from public.eventos_mensagens_recebidas e
  where e.id_empresa = p_id_empresa and e.identificador_externo = p_identificador_externo;
  return v_existente.resposta || jsonb_build_object('duplicated',true);
end;
$$;

