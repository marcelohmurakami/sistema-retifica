create or replace function public.salvar_insumos_servico(
  p_id_empresa bigint,
  p_id_servico bigint,
  p_insumos jsonb
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_produto_id bigint;
  v_quantidade numeric;
  v_total integer := 0;
begin
  if not private.usuario_tem_tipo_empresa(
    p_id_empresa,
    array['dono'::public.tipos_usuarios, 'gerente'::public.tipos_usuarios]
  ) then
    raise exception 'Voce nao possui permissao para configurar insumos.';
  end if;
  if not exists (
    select 1 from public.servicos s
    where s.id_empresa = p_id_empresa and s.id = p_id_servico
  ) then
    raise exception 'Servico invalido ou pertencente a outra empresa.';
  end if;
  if jsonb_typeof(coalesce(p_insumos, '[]'::jsonb)) <> 'array' then
    raise exception 'A lista de insumos e invalida.';
  end if;

  delete from public.servicos_insumos
  where id_empresa = p_id_empresa and id_servico = p_id_servico;

  for v_item in select value from jsonb_array_elements(coalesce(p_insumos, '[]'::jsonb))
  loop
    v_produto_id := nullif(v_item->>'id_produto', '')::bigint;
    v_quantidade := nullif(v_item->>'quantidade', '')::numeric;
    if v_produto_id is null or coalesce(v_quantidade, 0) <= 0 then
      raise exception 'Informe produto e quantidade validos para cada insumo.';
    end if;
    if not exists (
      select 1 from public.produtos p
      where p.id_empresa = p_id_empresa and p.id = v_produto_id
        and p.ativo and p.controla_estoque
    ) then
      raise exception 'O produto % nao esta ativo ou nao controla estoque.', v_produto_id;
    end if;
    insert into public.servicos_insumos (
      id_empresa, id_servico, id_produto, quantidade_padrao,
      descontar_comissao, ativo, criado_por
    ) values (
      p_id_empresa, p_id_servico, v_produto_id, v_quantidade,
      coalesce((v_item->>'descontar_comissao')::boolean, true), true, auth.uid()
    );
    v_total := v_total + 1;
  end loop;
  return v_total;
end;
$$;

