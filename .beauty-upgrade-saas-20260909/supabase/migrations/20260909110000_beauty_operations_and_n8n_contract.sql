create table if not exists public.servicos_insumos (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null,
  id_servico bigint not null,
  id_produto bigint not null,
  quantidade_padrao numeric(14,4) not null,
  descontar_comissao boolean not null default true,
  ativo boolean not null default true,
  criado_por uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint servicos_insumos_empresa_fkey foreign key (id_empresa)
    references public.empresas(id) on delete cascade,
  constraint servicos_insumos_servico_fkey foreign key (id_empresa, id_servico)
    references public.servicos(id_empresa, id) on delete cascade,
  constraint servicos_insumos_produto_fkey foreign key (id_empresa, id_produto)
    references public.produtos(id_empresa, id) on delete restrict,
  constraint servicos_insumos_quantidade_check check (quantidade_padrao > 0),
  constraint servicos_insumos_unique unique (id_empresa, id_servico, id_produto)
