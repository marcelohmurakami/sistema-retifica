create or replace function private.movimentar_estoque_comanda()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare r record;
begin
  if new.status = 'fechada' and old.status is distinct from 'fechada' then
    for r in
      select ci.id, ci.id_empresa, ci.id_produto, ci.quantidade, ci.descricao_snapshot
      from public.comandas_itens ci
      where ci.id_comanda = new.id and ci.tipo_item = 'produto'
    loop
      insert into public.movimentos_estoque (
        id_empresa,id_produto,tipo,quantidade,estoque_antes,estoque_depois,
        descricao,status,origem,id_comanda_item,movimentado_em,criado_por
      ) values (
        r.id_empresa,r.id_produto,'saida_venda',r.quantidade,0,0,
        'Venda na comanda #' || new.id || ' - ' || r.descricao_snapshot,
        'ativo','comanda',r.id,now(),auth.uid()
      ) on conflict (id_comanda_item) where id_comanda_item is not null and tipo = 'saida_venda'
        do nothing;
    end loop;

    for r in
      select c.id, c.id_empresa, c.id_comanda_item, c.id_produto,
             c.quantidade_utilizada, p.nome
      from public.consumos_insumos_comanda c
      join public.produtos p on p.id_empresa = c.id_empresa and p.id = c.id_produto
      where c.id_empresa = new.id_empresa and c.id_comanda = new.id
    loop
      insert into public.movimentos_estoque (
        id_empresa,id_produto,tipo,quantidade,estoque_antes,estoque_depois,
        descricao,status,origem,id_comanda_item,id_consumo_insumo,
        movimentado_em,criado_por
      ) values (
        r.id_empresa,r.id_produto,'saida_consumo',r.quantidade_utilizada,0,0,
        'Consumo na comanda #' || new.id || ' - ' || r.nome,
        'ativo','comanda',r.id_comanda_item,r.id,now(),auth.uid()
      ) on conflict (id_consumo_insumo) where id_consumo_insumo is not null and tipo = 'saida_consumo'
        do nothing;
    end loop;
  elsif new.status = 'cancelada' and old.status is distinct from 'cancelada' then
    update public.movimentos_estoque me
    set status = 'estornado', motivo_estorno = 'Cancelamento da comanda', updated_at = now()
    where (
      me.id_comanda_item in (
        select ci.id from public.comandas_itens ci where ci.id_comanda = new.id
      )
      or me.id_consumo_insumo in (
        select c.id from public.consumos_insumos_comanda c where c.id_comanda = new.id
      )
    ) and me.tipo in ('saida_venda', 'saida_consumo') and me.status = 'ativo';
  end if;
  return new;
end;
$$;

create or replace function private.gerar_comissoes_comanda()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  i record;
  v_regra_id bigint;
  v_tipo text;
  v_percentual numeric;
  v_valor_fixo numeric;
  v_base_tipo text;
  v_momento text;
  v_descontar_taxa boolean;
  v_descontar_insumos boolean;
  v_base_original numeric;
  v_base numeric;
  v_comissao numeric;
  v_total_itens numeric;
  v_taxa_rateada numeric;
  v_insumos numeric;
begin
  if new.status = 'fechada' and old.status is distinct from 'fechada' then
    select coalesce(sum(greatest(ci.valor_total, 0)), 0)
    into v_total_itens
    from public.comandas_itens ci
    where ci.id_comanda = new.id
      and ci.id_funcionario is not null
      and ci.tipo_item in ('servico', 'produto');

    for i in
      select ci.* from public.comandas_itens ci
      where ci.id_comanda = new.id
        and ci.id_funcionario is not null
        and ci.tipo_item in ('servico', 'produto')
    loop
      v_regra_id := null; v_tipo := null; v_percentual := null; v_valor_fixo := null;
      v_base_tipo := null; v_momento := null;
      v_descontar_taxa := true; v_descontar_insumos := true;

      select r.id, r.tipo_calculo, r.percentual, r.valor_fixo,
             r.base_calculo, r.momento_liberacao,
             r.descontar_taxa_pagamento, r.descontar_insumos
      into v_regra_id, v_tipo, v_percentual, v_valor_fixo,
           v_base_tipo, v_momento, v_descontar_taxa, v_descontar_insumos
      from public.comissoes_regras r
      where r.id_empresa = new.id_empresa and r.ativo
        and r.vigente_de <= current_date
        and (r.vigente_ate is null or r.vigente_ate >= current_date)
        and (r.id_funcionario is null or r.id_funcionario = i.id_funcionario)
        and (
          r.tipo_item = 'todos'
          or (i.tipo_item = 'servico' and r.tipo_item = 'servico'
              and (r.id_servico is null or r.id_servico = i.id_servico))
          or (i.tipo_item = 'produto' and r.tipo_item = 'produto'
              and (r.id_produto is null or r.id_produto = i.id_produto))
        )
      order by (r.id_funcionario is not null) desc,
        (r.id_servico is not null or r.id_produto is not null) desc,
        r.prioridade desc, r.vigente_de desc, r.id desc
      limit 1;

      if v_regra_id is null and i.comissao_tipo_snapshot is not null
         and i.comissao_valor_snapshot is not null then
        v_tipo := case when i.comissao_tipo_snapshot = 'fixo' then 'valor_fixo'
                       else i.comissao_tipo_snapshot end;
        v_percentual := case when i.comissao_tipo_snapshot = 'percentual'
                             then i.comissao_valor_snapshot end;
        v_valor_fixo := case when i.comissao_tipo_snapshot = 'fixo'
                             then i.comissao_valor_snapshot end;
        v_base_tipo := 'liquido_desconto';
        v_momento := 'fechamento_comanda';
      end if;

      if v_tipo is not null then
        v_base_original := case when v_base_tipo = 'bruto'
          then i.quantidade * i.valor_unitario_snapshot
          else greatest(i.valor_total, 0)
        end;
        v_taxa_rateada := case
          when v_descontar_taxa and v_total_itens > 0
          then round(new.taxa_pagamento_snapshot * greatest(i.valor_total, 0) / v_total_itens, 2)
          else 0 end;
        select coalesce(sum(c.custo_total), 0)
        into v_insumos
        from public.consumos_insumos_comanda c
        where c.id_empresa = new.id_empresa and c.id_comanda_item = i.id
          and c.descontar_comissao and v_descontar_insumos;
        v_base := greatest(round(v_base_original - v_taxa_rateada - v_insumos, 2), 0);
        v_comissao := case when v_tipo = 'percentual'
          then round(v_base * v_percentual / 100, 2)
          else round(i.quantidade * v_valor_fixo, 2)
        end;

        if v_comissao > 0 then
          insert into public.lancamentos_comissao (
            id_empresa,id_funcionario,id_regra,id_comanda,id_comanda_item,
            tipo_origem,tipo_item,descricao_snapshot,desconto_rateado,
            base_original,taxa_pagamento_rateada,custo_insumos_rateado,
            base_calculo,tipo_calculo,percentual_snapshot,valor_fixo_snapshot,
            valor_comissao,valor_pago,status,competencia,momento_liberacao,liberada_em
          ) values (
            new.id_empresa,i.id_funcionario,v_regra_id,new.id,i.id,
            'comanda',i.tipo_item,i.descricao_snapshot,i.desconto,
            v_base_original,v_taxa_rateada,v_insumos,v_base,
            v_tipo,v_percentual,v_valor_fixo,v_comissao,0,
            case when v_momento = 'fechamento_comanda' then 'liberada' else 'prevista' end,
            current_date,v_momento,
            case when v_momento = 'fechamento_comanda' then now() end
          ) on conflict (id_comanda_item) do nothing;
        end if;
      end if;
    end loop;
  elsif new.status = 'cancelada' and old.status is distinct from 'cancelada' then
    update public.lancamentos_comissao
    set status = 'estornada', estornada_em = now(),
        motivo_estorno = 'Cancelamento da comanda', updated_at = now()
    where id_comanda = new.id and valor_pago = 0
      and status not in ('paga', 'parcial', 'estornada');
  end if;
  return new;
end;
$$;

