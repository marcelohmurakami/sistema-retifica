create table if not exists public.unidades (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null,
  nome text not null,
  codigo text not null,
  telefone text,
  email text,
  endereco text,
  numero text,
  complemento text,
  bairro text,
  cidade text,
