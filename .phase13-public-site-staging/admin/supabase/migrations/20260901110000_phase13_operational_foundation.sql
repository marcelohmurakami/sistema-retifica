  sinal_status, sinal_valor, pagamento_status, pagamento_externo_id, valor_total
on public.agendamentos
for each row execute function private.registrar_historico_agendamento();

create or replace function private.sincronizar_preferencias_lembrete_site()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.site_notification_preferences is null then
    return new;
  end if;

  insert into public.preferencias_lembrete (
    id_empresa, id_cliente, whatsapp, email, sms, push,
    antecedencias_minutos, ativo, origem, updated_at
  ) values (
    new.id_empresa,
    new.id_cliente,
    coalesce((new.site_notification_preferences->>'whatsapp')::boolean, true),
    coalesce((new.site_notification_preferences->>'email')::boolean, true),
    false,
    false,
    array[1440, 120],
    true,
    'site',
    now()
  )
  on conflict (id_empresa, id_cliente) do update
  set whatsapp = excluded.whatsapp,
      email = excluded.email,
      ativo = true,
      origem = 'site',
      updated_at = now();

  return new;
end;
$$;

insert into public.preferencias_lembrete (
  id_empresa, id_cliente, whatsapp, email, sms, push,
  antecedencias_minutos, ativo, origem, updated_at
)
select distinct on (a.id_empresa, a.id_cliente)
  a.id_empresa,
  a.id_cliente,
  coalesce((a.site_notification_preferences->>'whatsapp')::boolean, true),
  coalesce((a.site_notification_preferences->>'email')::boolean, true),
  false,
  false,
  array[1440, 120],
  true,
  'site',
  a.updated_at
from public.agendamentos a
where a.site_notification_preferences is not null
order by a.id_empresa, a.id_cliente, a.updated_at desc
on conflict (id_empresa, id_cliente) do update
set whatsapp = excluded.whatsapp,
    email = excluded.email,
    ativo = excluded.ativo,
    origem = excluded.origem,
    updated_at = excluded.updated_at;

drop trigger if exists agendamentos_sincronizar_preferencias_site on public.agendamentos;
