alter table public.horarios_funcionamento enable row level security;
alter table public.disponibilidades enable row level security;
alter table public.preferencias_lembrete enable row level security;
alter table public.politicas_cancelamento enable row level security;
alter table public.historico_agendamentos enable row level security;

create policy unidades_membros_leem on public.unidades
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));
create policy unidades_membros_gerenciam on public.unidades
for all to authenticated using (private.usuario_pertence_empresa(id_empresa))
with check (private.usuario_pertence_empresa(id_empresa));

create policy horarios_funcionamento_membros_leem on public.horarios_funcionamento
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));
create policy horarios_funcionamento_membros_gerenciam on public.horarios_funcionamento
for all to authenticated using (private.usuario_pertence_empresa(id_empresa))
with check (private.usuario_pertence_empresa(id_empresa));

create policy disponibilidades_membros_leem on public.disponibilidades
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));
create policy disponibilidades_membros_gerenciam on public.disponibilidades
for all to authenticated using (private.usuario_pertence_empresa(id_empresa))
with check (private.usuario_pertence_empresa(id_empresa));

create policy preferencias_lembrete_membros_leem on public.preferencias_lembrete
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));
create policy preferencias_lembrete_membros_gerenciam on public.preferencias_lembrete
for all to authenticated using (private.usuario_pertence_empresa(id_empresa))
with check (private.usuario_pertence_empresa(id_empresa));

create policy politicas_cancelamento_membros_leem on public.politicas_cancelamento
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));
create policy politicas_cancelamento_membros_gerenciam on public.politicas_cancelamento
for all to authenticated using (private.usuario_pertence_empresa(id_empresa))
with check (private.usuario_pertence_empresa(id_empresa));

create policy historico_agendamentos_membros_leem on public.historico_agendamentos
for select to authenticated using (private.usuario_pertence_empresa(id_empresa));

revoke all on public.unidades, public.horarios_funcionamento,
  public.disponibilidades, public.preferencias_lembrete,
  public.politicas_cancelamento, public.historico_agendamentos
from anon;

grant select, insert, update, delete on public.unidades,
  public.horarios_funcionamento, public.disponibilidades,
  public.preferencias_lembrete, public.politicas_cancelamento
to authenticated;

grant select on public.historico_agendamentos,
  public.profissionais, public.profissionais_servicos, public.notificacoes
to authenticated;

do $$
declare
  v_sequence regclass;
begin
  foreach v_sequence in array array[
    'public.unidades_id_seq'::regclass,
    'public.horarios_funcionamento_id_seq'::regclass,
    'public.disponibilidades_id_seq'::regclass,
    'public.preferencias_lembrete_id_seq'::regclass,
    'public.politicas_cancelamento_id_seq'::regclass,
    'public.historico_agendamentos_id_seq'::regclass
  ]
  loop
    execute format('grant usage, select on sequence %s to authenticated', v_sequence);
  end loop;
end;
$$;

comment on table public.unidades is 'Unidades físicas de cada empresa; todo agendamento pertence a uma unidade.';
comment on table public.horarios_funcionamento is 'Jornada pública da unidade, separada da jornada individual dos profissionais.';
comment on table public.disponibilidades is 'Exceções versionadas de disponibilidade por profissional e unidade.';
comment on table public.historico_agendamentos is 'Histórico imutável de criação, status, reagendamento, cancelamento e pagamento.';
comment on table public.preferencias_lembrete is 'Preferências persistentes de comunicação do cliente por empresa.';
comment on table public.politicas_cancelamento is 'Regras de antecedência, atraso, sinal e cancelamento por empresa ou unidade.';
