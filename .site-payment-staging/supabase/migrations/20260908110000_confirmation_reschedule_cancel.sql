create or replace function public.reivindicar_estornos_agendamento(
  p_limite integer default 20,
  p_id_agendamento bigint default null
)
returns table (
  request_id bigint,
  company_id bigint,
  booking_id bigint,
  payment_id bigint,
  order_id text,
  amount numeric,
  idempotency_key uuid
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  with escolhidas as (
    select r.id from public.solicitacoes_estorno_agendamento r
    where r.status in ('pendente', 'falhou')
      and r.proxima_tentativa_em <= now()
      and r.tentativas < 5
      and (p_id_agendamento is null or r.id_agendamento = p_id_agendamento)
    order by r.id
    limit least(greatest(coalesce(p_limite, 20), 1), 100)
    for update skip locked
  ), atualizadas as (
    update public.solicitacoes_estorno_agendamento r
    set status = 'processando', tentativas = r.tentativas + 1, updated_at = now()
    from escolhidas e where r.id = e.id
    returning r.*
  )
  select r.id, r.id_empresa, r.id_agendamento, r.id_pagamento,
    p.identificador_externo, r.valor, r.chave_idempotencia
  from atualizadas r
  join public.pagamentos p
    on p.id_empresa = r.id_empresa and p.id = r.id_pagamento;
end;
$$;

create or replace function public.concluir_estorno_agendamento(
  p_solicitacao_id bigint,
  p_provedor_status text,
  p_provedor_status_detalhe text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_solicitacao public.solicitacoes_estorno_agendamento%rowtype;
begin
  select * into v_solicitacao
  from public.solicitacoes_estorno_agendamento r
  where r.id = p_solicitacao_id for update;
  if not found then raise exception 'Solicitacao de estorno nao encontrada.'; end if;
  if v_solicitacao.status = 'confirmado' then return; end if;
  if v_solicitacao.status <> 'processando' then
    raise exception 'Solicitacao de estorno nao esta em processamento.';
  end if;

  update public.solicitacoes_estorno_agendamento
  set status = 'confirmado', provedor_status = p_provedor_status,
      provedor_status_detalhe = p_provedor_status_detalhe,
      processado_em = now(), ultimo_erro = null, updated_at = now()
  where id = p_solicitacao_id;
  update public.pagamentos
  set status = 'estornado', estornado_em = coalesce(estornado_em, now()),
      motivo_estorno = coalesce(motivo_estorno, v_solicitacao.motivo), updated_at = now()
  where id_empresa = v_solicitacao.id_empresa and id = v_solicitacao.id_pagamento;
  update public.agendamentos
  set sinal_status = 'estornado', pagamento_status = 'estornado', updated_at = now()
  where id_empresa = v_solicitacao.id_empresa and id = v_solicitacao.id_agendamento;
end;
$$;

create or replace function public.falhar_estorno_agendamento(
  p_solicitacao_id bigint,
  p_erro text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.solicitacoes_estorno_agendamento
  set status = case when tentativas >= 5 then 'revisao_manual' else 'falhou' end,
      ultimo_erro = left(coalesce(p_erro, 'Falha desconhecida.'), 1000),
      proxima_tentativa_em = now() + make_interval(mins => least(60, power(2, tentativas)::integer)),
      updated_at = now()
  where id = p_solicitacao_id and status = 'processando';
end;
$$;

