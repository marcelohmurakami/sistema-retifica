create or replace function private.emitir_token_link_agendamento(
  p_id_empresa bigint,
  p_id_agendamento bigint,
  p_finalidade text default 'gerenciar',
  p_validade interval default interval '7 days'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_token text;
  v_expira_em timestamptz;
begin
  if p_finalidade not in ('gerenciar', 'confirmar') then
    raise exception 'Finalidade de token invalida.';
  end if;
  if p_validade < interval '5 minutes' or p_validade > interval '30 days' then
    raise exception 'Validade do token fora do intervalo permitido.';
  end if;

  perform 1 from public.agendamentos a
  where a.id_empresa = p_id_empresa and a.id = p_id_agendamento
  for update;
  if not found then raise exception 'Agendamento nao encontrado.'; end if;

  update public.tokens_links_agendamento
  set revogado_em = now()
  where id_empresa = p_id_empresa
    and id_agendamento = p_id_agendamento
    and finalidade = p_finalidade
    and revogado_em is null;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  v_expira_em := now() + p_validade;

  insert into public.tokens_links_agendamento (
    id_empresa, id_agendamento, token_hash, finalidade, expira_em
  ) values (
    p_id_empresa, p_id_agendamento,
    encode(extensions.digest(v_token, 'sha256'), 'hex'),
    p_finalidade, v_expira_em
  );

  return jsonb_build_object('token', v_token, 'expires_at', v_expira_em);
end;
$$;

create or replace function public.consumir_token_link_agendamento(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_link public.tokens_links_agendamento%rowtype;
  v_booking_token uuid;
begin
  if p_token is null or p_token !~ '^[0-9a-fA-F]{64}$' then
    raise exception 'Link de confirmacao invalido.';
  end if;

  select * into v_link
  from public.tokens_links_agendamento t
  where t.token_hash = encode(extensions.digest(lower(p_token), 'sha256'), 'hex')
  for update;

  if not found
     or v_link.revogado_em is not null
     or v_link.expira_em <= now()
     or v_link.usos >= v_link.max_usos then
    raise exception 'Este link expirou ou ja atingiu o limite de uso.';
  end if;

  select a.site_access_token into v_booking_token
  from public.agendamentos a
  where a.id_empresa = v_link.id_empresa
    and a.id = v_link.id_agendamento
    and a.site_access_token is not null
    and coalesce(a.site_access_token_expires_at, now() - interval '1 second') > now();

  if v_booking_token is null then
    raise exception 'O acesso a este agendamento expirou.';
  end if;

  update public.tokens_links_agendamento
  set usos = usos + 1, ultimo_uso_em = now()
  where id = v_link.id;

  return jsonb_build_object(
    'company_id', v_link.id_empresa,
    'booking_id', v_link.id_agendamento,
    'booking_token', v_booking_token,
    'expires_at', least(v_link.expira_em, now() + interval '7 days')
  );
end;
$$;

