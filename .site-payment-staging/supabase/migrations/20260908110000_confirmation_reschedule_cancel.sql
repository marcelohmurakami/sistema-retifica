create or replace function private.obter_agendamento_site(p_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', a.id,
    'token', a.site_access_token,
    'codigo', 'MK' || lpad(a.id::text, 6, '0'),
    'status', a.status,
    'inicio', a.inicio,
    'fim', a.fim,
    'sinal_status', a.sinal_status,
    'sinal_valor', a.sinal_valor,
    'confirmado_em', a.confirmado_em,
    'confirmacao_origem', a.confirmacao_origem,
    'cancelado_em', a.cancelado_em,
    'motivo_cancelamento', a.motivo_cancelamento,
    'cancelamento_origem', a.cancelamento_origem,
    'estorno', (
      select jsonb_build_object('status', r.status, 'valor', r.valor)
      from public.solicitacoes_estorno_agendamento r
      where r.id_empresa = a.id_empresa and r.id_agendamento = a.id
      order by r.id desc limit 1
    ),
    'cliente', jsonb_build_object(
      'nome', c.nome, 'email', c.email, 'telefone', c.telefone_principal
    ),
    'empresa', jsonb_build_object(
      'id', e.id, 'nome', e.fantasia,
      'fuso_horario', coalesce(e.fuso_horario, 'America/Sao_Paulo')
    ),
    'servico', jsonb_build_object(
      'id', s.id, 'nome', s.nome,
      'duracao_minutos', item.duracao_minutos, 'preco', item.preco
    ),
    'profissional', jsonb_build_object(
      'id', f.id,
      'nome', regexp_replace(f.nome, '[[:space:]]*\(Teste\)[[:space:]]*$', '', 'i'),
      'cargo', coalesce(f.cargo, 'Profissional')
    ),
    'lembretes', coalesce(a.site_notification_preferences, '{}'::jsonb)
  )
  from public.agendamentos a
  join public.clientes c
    on c.id_empresa = a.id_empresa and c.id = a.id_cliente
  join public.empresas e on e.id = a.id_empresa
  join lateral (
    select i.* from public.agendamentos_servicos i
    where i.id_empresa = a.id_empresa and i.id_agendamento = a.id
    order by (i.status = 'cancelado'), i.ordem, i.id limit 1
  ) item on true
  join public.servicos s
    on s.id_empresa = item.id_empresa and s.id = item.id_servico
  join public.funcionarios f
    on f.id_empresa = item.id_empresa and f.id = item.id_funcionario
  where a.site_access_token = p_token
    and coalesce(a.site_access_token_expires_at, now() - interval '1 second') > now();
$$;

create or replace function private.aplicar_acao_agendamento_cliente(
  p_id_empresa bigint,
  p_id_agendamento bigint,
  p_acao text,
  p_motivo text,
  p_origem text,
  p_id_cliente bigint,
  p_usuario uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_agendamento public.agendamentos%rowtype;
  v_politica public.politicas_cancelamento%rowtype;
  v_pagamento public.pagamentos%rowtype;
  v_valor_estorno numeric(12,2);
  v_status_estorno text;
begin
  select * into v_agendamento
  from public.agendamentos a
  where a.id_empresa = p_id_empresa and a.id = p_id_agendamento
  for update;
  if not found then raise exception 'Agendamento nao encontrado.'; end if;

  if p_acao = 'confirmar' then
    if v_agendamento.status = 'confirmado' then return; end if;
    if v_agendamento.status not in ('aguardando_confirmacao', 'aguardando_pagamento') then
      raise exception 'Este agendamento nao pode ser confirmado.';
    end if;
    if v_agendamento.sinal_status = 'pendente' then
      raise exception 'O pagamento do sinal ainda esta pendente.';
    end if;
    if v_agendamento.inicio <= now() then
      raise exception 'Agendamentos passados nao podem ser confirmados.';
    end if;

    update public.agendamentos
    set status = 'confirmado',
        confirmado_em = coalesce(confirmado_em, now()),
        confirmacao_origem = p_origem,
        updated_at = now()
    where id_empresa = p_id_empresa and id = p_id_agendamento;
    return;
  end if;

  if p_acao <> 'cancelar' then raise exception 'Acao invalida.'; end if;
  if v_agendamento.status = 'cancelado' then return; end if;
  if v_agendamento.status in ('finalizado', 'no_show', 'em_atendimento') then
    raise exception 'Este agendamento nao pode mais ser cancelado.';
  end if;
  if char_length(coalesce(p_motivo, '')) > 500 then
    raise exception 'O motivo pode ter no maximo 500 caracteres.';
  end if;

  select * into v_politica
  from public.politicas_cancelamento p
  where p.id_empresa = p_id_empresa and p.ativo
    and current_date between p.vigente_desde and coalesce(p.vigente_ate, 'infinity'::date)
    and (p.id_unidade = v_agendamento.id_unidade or p.id_unidade is null)
  order by (p.id_unidade = v_agendamento.id_unidade) desc,
    p.vigente_desde desc, p.id desc limit 1;

  if v_agendamento.inicio <= now() + make_interval(
    mins => coalesce(v_politica.antecedencia_cancelamento_minutos, 1440)
  ) then
    raise exception 'O prazo para cancelamento online desta reserva ja terminou.';
  end if;

  update public.agendamentos
  set status = 'cancelado', cancelado_em = coalesce(cancelado_em, now()),
      motivo_cancelamento = coalesce(nullif(btrim(p_motivo), ''), 'Cancelado pelo cliente.'),
      cancelamento_origem = p_origem,
      cancelado_por_cliente = p_id_cliente,
      cancelado_por_usuario = p_usuario,
      updated_at = now()
  where id_empresa = p_id_empresa and id = p_id_agendamento;

  perform private.cancelar_mensagens_agendamento(p_id_empresa, p_id_agendamento);
  update public.tokens_links_agendamento
  set revogado_em = now()
  where id_empresa = p_id_empresa and id_agendamento = p_id_agendamento
    and revogado_em is null;

  update public.pagamentos
  set status = 'cancelado', updated_at = now(),
      observacoes = concat_ws(E'\n', observacoes, 'Cancelado junto com o agendamento antes do pagamento.')
  where id_empresa = p_id_empresa and id_agendamento = p_id_agendamento
    and status in ('pendente', 'processando');

  update public.agendamentos
  set pagamento_status = 'cancelado', updated_at = now()
  where id_empresa = p_id_empresa and id = p_id_agendamento
    and pagamento_status in ('pendente', 'processando', 'falhou');

  select * into v_pagamento
  from public.pagamentos p
  where p.id_empresa = p_id_empresa and p.id_agendamento = p_id_agendamento
    and p.status = 'confirmado'
  order by p.id desc limit 1 for update;

  if found and v_agendamento.sinal_status = 'pago' then
    v_valor_estorno := greatest(
      round(v_pagamento.valor - (
        v_agendamento.valor_total * coalesce(v_politica.multa_cancelamento_percentual, 0) / 100
      ), 2),
      0
    );
    if v_valor_estorno > 0 then
      v_status_estorno := case
        when v_valor_estorno <> v_pagamento.valor then 'revisao_manual'
        when v_pagamento.provedor = 'mercado_pago'
             and v_pagamento.identificador_externo is not null then 'pendente'
        else 'revisao_manual'
      end;
      insert into public.solicitacoes_estorno_agendamento (
        id_empresa, id_agendamento, id_pagamento, valor, status, motivo
      ) values (
        p_id_empresa, p_id_agendamento, v_pagamento.id, v_valor_estorno,
        v_status_estorno, 'Estorno solicitado conforme politica de cancelamento.'
      ) on conflict do nothing;
    end if;
  end if;

  perform private.enfileirar_mensagem_agendamento(
    p_id_empresa, p_id_agendamento, 'cancelamento', false
  );
end;
$$;

create or replace function private.alterar_agendamento_site(
