create or replace function private.enfileirar_mensagem_agendamento(
  p_id_empresa bigint,
  p_id_agendamento bigint,
  p_tipo text,
  p_gerar_link boolean default true
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_agendamento public.agendamentos%rowtype;
  v_cliente public.clientes%rowtype;
  v_preferencias jsonb;
  v_emitido jsonb;
  v_link text;
  v_assunto text;
  v_conteudo text;
  v_chave text;
begin
  select * into v_agendamento
  from public.agendamentos a
  where a.id_empresa = p_id_empresa and a.id = p_id_agendamento;
  if not found then return; end if;

  select * into v_cliente
  from public.clientes c
  where c.id_empresa = p_id_empresa and c.id = v_agendamento.id_cliente;
  if not found then return; end if;

  v_preferencias := coalesce(v_agendamento.site_notification_preferences, '{}'::jsonb);
  if p_gerar_link then
    v_emitido := private.emitir_token_link_agendamento(
      p_id_empresa, p_id_agendamento, 'gerenciar', interval '7 days'
    );
    v_link := '/confirmacao/acessar?token=' || (v_emitido->>'token');
  end if;

  v_assunto := case p_tipo
    when 'reagendamento' then 'Seu novo horario foi reservado'
    when 'cancelamento' then 'Cancelamento do agendamento'
    else 'Confirme seu agendamento'
  end;
  v_conteudo := case p_tipo
    when 'reagendamento' then 'Seu agendamento foi reagendado. Confira os novos dados no link seguro.'
    when 'cancelamento' then 'Seu cancelamento foi registrado. Consulte os detalhes na sua area do cliente.'
    else 'Seu horario foi reservado. Use o link seguro para consultar e confirmar.'
  end;
  v_chave := p_tipo || ':' || p_id_agendamento::text || ':' ||
    coalesce(v_emitido->>'token', extract(epoch from clock_timestamp())::bigint::text);

  if coalesce((v_preferencias->>'email')::boolean, true)
     and nullif(btrim(v_cliente.email), '') is not null then
    insert into public.fila_mensagens (
      id_empresa, id_cliente, canal, destinatario, assunto, conteudo,
      dados_template, status, prioridade, agendada_para,
      tentativas, max_tentativas, chave_idempotencia
    ) values (
      p_id_empresa, v_cliente.id, 'email', lower(btrim(v_cliente.email)),
      v_assunto, v_conteudo,
      jsonb_build_object(
        'tipo', p_tipo, 'agendamento_id', p_id_agendamento,
        'inicio', v_agendamento.inicio, 'link_relativo', v_link,
        'token_expira_em', v_emitido->>'expires_at'
      ),
      'pendente', 100, now(), 0, 5, v_chave || ':email'
    );
  end if;

  if coalesce((v_preferencias->>'whatsapp')::boolean, true)
     and nullif(btrim(coalesce(v_cliente.telefone_e164, v_cliente.telefone_principal)), '') is not null then
    insert into public.fila_mensagens (
      id_empresa, id_cliente, canal, destinatario, assunto, conteudo,
      dados_template, status, prioridade, agendada_para,
      tentativas, max_tentativas, chave_idempotencia
    ) values (
      p_id_empresa, v_cliente.id, 'whatsapp',
      btrim(coalesce(v_cliente.telefone_e164, v_cliente.telefone_principal)),
      v_assunto, v_conteudo,
      jsonb_build_object(
        'tipo', p_tipo, 'agendamento_id', p_id_agendamento,
        'inicio', v_agendamento.inicio, 'link_relativo', v_link,
        'token_expira_em', v_emitido->>'expires_at'
      ),
      'pendente', 100, now(), 0, 5, v_chave || ':whatsapp'
    );
  end if;
end;
$$;

